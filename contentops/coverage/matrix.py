"""The bundled MITRE ATT&CK Enterprise matrix -- the one loader for coverage.

Every coverage surface (heatmap, gaps, badge, Navigator layer, report,
portfolio) reads the matrix through :func:`load_matrix`, so they agree on
which technique ids exist, which tactics each belongs to, and how retired
ids map to their replacements.

The data file (``data/mitre_attack_full.json``) is generated by
``scripts/refresh_attack_matrix.py`` from MITRE's STIX bundle and carries,
besides the tactic / technique / sub-technique tables:

* ``attack_version`` -- the ATT&CK release (e.g. ``"19.2"``);
* ``revoked`` -- ``{old_id: current_id}`` with chains resolved, so a
  detection still tagged with a retired id (T1562.001 -> T1685) is credited
  to its replacement instead of silently scoring zero;
* ``deprecated`` -- retired ids with no replacement (reported, not counted).

Older data files without those keys load with empty values.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from functools import lru_cache
from importlib import resources
from types import MappingProxyType
from typing import Any, Literal, Mapping

from contentops.core.metadata import TECHNIQUE_ID_RE

# The 14 Enterprise tactics in kill-chain (render) order.
ENTERPRISE_TACTICS: tuple[str, ...] = (
    "Reconnaissance",
    "ResourceDevelopment",
    "InitialAccess",
    "Execution",
    "Persistence",
    "PrivilegeEscalation",
    "DefenseEvasion",
    "CredentialAccess",
    "Discovery",
    "LateralMovement",
    "Collection",
    "CommandAndControl",
    "Exfiltration",
    "Impact",
)

# ARM Microsoft.SecurityInsights/alertRules tactic enum members outside the
# Enterprise list (legacy PreAttack, two ICS/OT tactics). Rules may carry
# them; no Enterprise technique belongs to them.
ARM_EXTRA_TACTICS: tuple[str, ...] = (
    "PreAttack",
    "ImpairProcessControl",
    "InhibitResponseFunction",
)

ALL_TACTICS: tuple[str, ...] = ENTERPRISE_TACTICS + ARM_EXTRA_TACTICS

# Case/separator-insensitive lookup, plus the upstream short-names MITRE
# now files Defense Evasion techniques under.
_TACTIC_LOOKUP: dict[str, str] = {t.lower(): t for t in ALL_TACTICS}
_TACTIC_LOOKUP.update({
    "stealth": "DefenseEvasion",
    "defenseimpairment": "DefenseEvasion",
})
_TACTIC_SEPARATORS = re.compile(r"[\s_\-]+")

TechniqueStatus = Literal["current", "revoked", "deprecated", "unknown"]


def normalise_technique_id(value: object) -> str | None:
    """``" t1059.001 "`` -> ``"T1059.001"``; anything malformed -> ``None``."""
    if not isinstance(value, str):
        return None
    candidate = value.strip().upper()
    return candidate if TECHNIQUE_ID_RE.fullmatch(candidate) else None


def normalise_tactic(value: object) -> str | None:
    """``"credential access"`` / ``"Credential_Access"`` -> ``"CredentialAccess"``."""
    if not isinstance(value, str):
        return None
    return _TACTIC_LOOKUP.get(_TACTIC_SEPARATORS.sub("", value).lower())


@dataclass(frozen=True)
class AttackMatrix:
    """Immutable view of one ATT&CK Enterprise release."""

    attack_version: str
    tactics: frozenset[str]
    techniques: frozenset[str]          # parent technique ids
    sub_techniques: frozenset[str]      # T####.### ids
    technique_tactics: Mapping[str, tuple[str, ...]]
    names: Mapping[str, str]
    revoked: Mapping[str, str] = field(default_factory=lambda: MappingProxyType({}))
    deprecated: frozenset[str] = frozenset()
    label: str = "MITRE ATT&CK Enterprise (full)"

    @property
    def attack_major(self) -> str:
        """Major release (``"19"`` for ``"19.2"``); empty when unknown."""
        return self.attack_version.split(".", 1)[0] if self.attack_version else ""

    def is_current(self, technique_id: str) -> bool:
        return technique_id in self.technique_tactics

    def resolve(self, technique_id: str) -> tuple[str | None, TechniqueStatus]:
        """Map an id to the current matrix.

        Returns ``(id, "current")``, ``(replacement, "revoked")``,
        ``(None, "deprecated")`` or ``(None, "unknown")``.
        """
        if technique_id in self.technique_tactics:
            return technique_id, "current"
        replacement = self.revoked.get(technique_id)
        if replacement and replacement in self.technique_tactics:
            return replacement, "revoked"
        if technique_id in self.deprecated:
            return None, "deprecated"
        return None, "unknown"

    def tactics_for(self, technique_id: str) -> tuple[str, ...]:
        return self.technique_tactics.get(technique_id, ())

    @classmethod
    def from_dict(cls, raw: Mapping[str, Any]) -> AttackMatrix:
        technique_tactics: dict[str, tuple[str, ...]] = {}
        names: dict[str, str] = {}
        parents: set[str] = set()
        subs: set[str] = set()
        for key, bucket in (("techniques", parents), ("sub_techniques", subs)):
            for entry in raw.get(key) or []:
                tid = entry.get("id")
                if not isinstance(tid, str):
                    continue
                bucket.add(tid)
                tactics = tuple(
                    t for t in (normalise_tactic(x) for x in entry.get("tactics") or [])
                    if t is not None
                )
                technique_tactics[tid] = tuple(dict.fromkeys(tactics))
                names[tid] = str(entry.get("name") or "")
        tactics = frozenset(
            t["id"] for t in raw.get("tactics") or [] if isinstance(t.get("id"), str)
        )
        revoked = {
            str(old): str(new) for old, new in (raw.get("revoked") or {}).items()
            if isinstance(old, str) and isinstance(new, str)
        }
        return cls(
            attack_version=str(raw.get("attack_version") or ""),
            tactics=tactics,
            techniques=frozenset(parents),
            sub_techniques=frozenset(subs),
            technique_tactics=MappingProxyType(technique_tactics),
            names=MappingProxyType(names),
            revoked=MappingProxyType(revoked),
            deprecated=frozenset(
                d for d in raw.get("deprecated") or [] if isinstance(d, str)
            ),
        )


def _data_text(filename: str) -> str:
    return (resources.files("contentops.coverage.data") / filename).read_text(
        encoding="utf-8",
    )


@lru_cache(maxsize=1)
def load_matrix() -> AttackMatrix:
    """Load (once per process) the bundled full Enterprise matrix."""
    return AttackMatrix.from_dict(json.loads(_data_text("mitre_attack_full.json")))


